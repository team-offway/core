-- #280 배포 선행 조건 — 사용자 데이터를 비운다. **머지 전에 한 번 돌린다.**
--
-- ## 왜 필요한가
--
-- V20260818205131 이 guest_id 를 지우고 user_id 를 NOT NULL + UNIQUE 로 추가한다. 기존 행에는
-- 채울 값이 없어 MySQL 이 전부 제로 바이트로 채우고, UNIQUE 에서 서로 중복이 되어 ERROR 1062 다.
-- 실측(로컬 MySQL 8.4): leave_balance 가 0행이면 성공, 1행이면 성공하지만 소유자가
-- 00000000-0000-0000-0000-000000000000 이 되고, **2행부터 실패**한다. 2026-08-24 운영은 13행이다.
--
-- 더 나쁜 것은 실패 시점이다. MySQL 의 DDL 은 트랜잭션이 아니라 되돌지 않아, course 를 이미 바꾼
-- 뒤 leave_balance 에서 멈춘다 — 두 테이블이 서로 다른 시대에 남는다. 배포가 컨테이너를 옛 이미지로
-- 되돌려도 그쪽은 guest_id 를 기대하므로(prod 는 ddl-auto=validate) 함께 부팅에 실패한다.
-- **되돌아갈 곳이 없어진다.**
--
-- ## 왜 backfill 하지 않는가
--
-- 살릴 수 있는 것이 거의 없고, 살리는 규칙을 정할 근거도 없다. 실측(2026-08-24):
--
--   user_guest_link 에 연결된 사용자        3명 (키 1개 2명 + 키 3개 1명)
--   그 사용자들의 leave_balance 행           5행 — 105 · 99 · 106 · 106.25 · 114
--
-- leave_balance 는 UNIQUE(user_id) 라 사용자당 한 행이다. 키를 셋 가진 사용자는 backfill 하면 한
-- 사용자에 여러 행이 생겨 같은 ERROR 1062 가 난다. 105·99·106 중 무엇이 그 사람의 실제 연차인지
-- **정할 근거가 없다** — 게스트 키는 검증된 적 없는 값이라 어느 행이 정말 누구 것인지 확정할 수 없다.
-- 그 3명을 위해 마이그레이션을 다시 쓰고 병합 규칙을 만드는 값어치가 없다.
--
-- ## 언제 돌리나 — 머지 전이다
--
-- dev 푸시가 곧 배포다(deploy.yml 의 `push: branches: [dev]`). 머지와 배포 사이에 손을 넣을 창이
-- 없으므로 **머지하기 전에** 비워야 한다. 비운 뒤 머지 전까지는 옛 코드가 빈 테이블로 도는데,
-- 신규 서비스와 같은 상태라 문제없다.
--
-- 되돌릴 수 없다. 배포 파이프라인에 백업 단계가 없으므로 **먼저 mysqldump 를 받는다.**
--
--   docker exec offway-mysql mysqldump -u"$U" -p"$P" offway > ~/offway-before-280.sql
--
-- ## 적재분은 건드리지 않는다
--
-- region_poi · poi_intro · gallery_photo · hub_attraction · region_content 와 batch_run 은
-- 그대로 둔다. 함께 비우면 부팅에서 배치가 전부 다시 돌아 국문관광정보 하루 한도(1,000)를 넘긴다 —
-- RegionPoi 267 + PoiIntro 712 + RegionContent 130 + HubAttraction 89 = 약 1,198. 한도가 마르면
-- 그날 코스 생성이 degrade 된다. 관광사진갤러리(1,790건 생존확인)도 같은 이유다.
--
-- **둘 중 하나만 비우는 것이 가장 나쁘다.** batch_run 만 비우면 배치가 "아직 안 돌았다" 로 읽어 그
-- 호출이 나가고, region_poi 만 비우면 "이미 돌았다" 로 읽어 다시 안 채워 홈 장소 카드가 다음
-- 크론(월 1회)까지 빈다. 함께 남긴다.
--
-- flyway_schema_history 도 남긴다. 지우면 Flyway 가 처음부터 다시 적용하려 든다. 테이블만 DROP 하고
-- 이력을 남기는 것은 더 나쁘다 — "적용됨" 으로 읽어 테이블을 안 만들고, validate 가 부팅을 막는다.
--
