package com.offway.core.liveactivity.infrastructure.apns;

/**
 * APNs 발송 한 건의 결과(#575).
 *
 * <p><b>실패를 하나로 뭉치지 않는다.</b> "이 토큰은 죽었다" 와 "지금 못 보냈다" 는 대응이 정반대다 —
 * 전자는 행을 지워야 하고(계속 두면 매번 실패한다), 후자는 지우면 안 된다(다음에 성공할 토큰을 잃는다).
 * 그 구분을 상태코드 비교로 호출부마다 하면 한 곳만 놓쳐도 멀쩡한 토큰이 사라진다.
 */
public enum ApnsResult {

    /** 보냈다. */
    SENT,

    /**
     * 이 토큰은 더 이상 유효하지 않다 — 행을 지운다.
     *
     * <p>{@code 410 Gone}(카드가 내려갔다)과 {@code 400 BadDeviceToken}(형식이 틀렸거나 <b>다른
     * 환경의 토큰</b>)이 여기다. 잠금화면 카드는 iOS 가 최대 8시간 뒤 스스로 끝내므로, 하루 한 번
     * 도는 갱신은 <b>이 결과를 자주 본다. 그것이 정상이다</b> — 앱이 다시 띄우면서 새 토큰을 올린다.
     */
    GONE,

    /** 이번에는 못 보냈다 — 네트워크·5xx·일시 오류. 토큰은 살아 있을 수 있으므로 지우지 않는다. */
    FAILED,

    /**
     * APNs 가 물러나라고 했다({@code 429}).
     *
     * <p>{@link #FAILED} 와 가르는 이유는 <b>다음 한 건을 보내도 되는가</b>가 다르기 때문이다. 일시
     * 오류는 다음 기기에서 성공할 수 있지만, 속도 제한은 상대가 지금 우리 전체를 밀어내는 중이라
     * 이어서 쏘면 제한만 길어진다.
     */
    THROTTLED,

    /** 보낼 수단이 없다 — {@code .p8} 설정이 없어 발송이 비활성이다. 실패로 세지 않는다. */
    DISABLED
}
