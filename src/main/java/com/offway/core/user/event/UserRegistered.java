/**
 * 새 사용자가 가입했다(#610) — <b>사람이 들어왔다</b>는 신호다.
 *
 * <h2>왜 이벤트인가</h2>
 *
 * <p>{@code AuthService} 가 알림을 직접 보내면 <b>인증 흐름이 통보 책임을 떠안는다.</b> 로그인은 신원을
 * 확인해 토큰을 내주는 일이고, 누구에게 무엇을 알리는지는 그 일이 아니다. {@link UserWithdrawn} 을
 * 이벤트로 둔 것과 같은 판단이다.
 *
 * <h2>왜 userId 를 싣지 않나</h2>
 *
 * <p>지금 이 이벤트를 받는 쪽은 <b>디스코드 알림 하나</b>이고, 그 알림에 개인을 특정할 값을 싣지 않기로
 * 정했다(이슈 #610). 이벤트에 식별자를 실어 두면 "받는 쪽이 안 쓰면 된다" 가 되는데, 그건 규칙이 아니라
 * 습관에 맡기는 것이다 — <b>실을 수 없게 만드는 편</b>이 낫다.
 *
 * <p>사용자별 후속 작업(환영 푸시 등)이 생기면 그때 {@code userId} 를 더한다. 그 작업은 개인을 알아야
 * 하는 것이 정당하므로, 필요해진 자리에서 정하면 된다.
 *
 * @param provider 어느 경로로 가입했나 — {@code KAKAO}·{@code APPLE}·{@code GOOGLE}.
 *     개인 식별력은 없고, "어느 로그인이 실제로 쓰이는가" 에 답한다
 */
public record UserRegistered(String provider) {}
