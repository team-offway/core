package com.offway.core.user.domain;

/**
 * refresh 토큰을 왜 폐기했나(#389).
 *
 * <p><b>"방금 폐기됐다" 만으로는 부족해서 생겼다.</b> 회전 직후 유예 창 안에 같은 refresh 가 다시 오면
 * 응답 유실로 보고 새 쌍을 다시 발급하는데, 판정을 폐기 시각만으로 하면 <b>로그아웃도 방금 폐기한 것</b>
 * 이라 그 창을 통과한다 — 로그아웃한 뒤 10초 동안 그 토큰으로 세션을 되살릴 수 있게 된다.
 *
 * <p>탈취 감지로 전량 폐기한 직후도 같다. 끊으려고 끊은 것을 되살려 주면 그 방어가 사라진다.
 */
public enum RevokedReason {

    /** 재발급으로 회전됐다 — 뒤이어 새 토큰이 나갔다. <b>이것만</b> 유예 창 복구의 대상이다. */
    ROTATED,

    /** 사용자가 로그아웃했다. 되살리면 안 된다. */
    LOGOUT,

    /** 폐기된 토큰이 다시 와서 탈취로 보고 끊었다. 되살리면 방어가 무의미해진다. */
    REUSE_DETECTED;

    /** 유예 창 안이라도 되살릴 수 있는 폐기인가 — 회전만 그렇다. */
    public boolean recoverable() {
        return this == ROTATED;
    }

    /**
     * 이 토큰이 다시 왔을 때 <b>탈취 경보를 울릴 값인가</b>.
     *
     * <p>회전으로 폐기된 것만 그렇다. 정상 클라이언트는 회전된 토큰을 다시 쓰지 않으므로, 유예 창 밖에서
     * 그것이 오면 탈취 정황이고 남은 세션까지 끊는 것이 맞다.
     *
     * <p><b>로그아웃은 다르다.</b> 사용자가 그 세션을 스스로 끝냈고, 앱이 그 토큰을 한 번 더 보내는 것은
     * 흔한 뒷북일 뿐이다. 그걸 탈취로 읽으면 <b>다른 기기가 전부 끊긴다</b> — 기기별 로그아웃을 만들어 놓고
     * 그 뒤에 한 번 더 온 요청이 결국 전체 로그아웃을 일으키는 셈이다.
     *
     * <p>탈취 감지로 끊은 것도 울릴 이유가 없다. 이미 그 사용자의 토큰이 전부 폐기된 뒤라 더 끊을 것이 없다.
     */
    public boolean alarmsOnReuse() {
        return this == ROTATED;
    }
}
