package com.offway.core.region.domain;

/**
 * 지역에 붙는 라벨 종류. 정책 매칭·필터의 기준.
 *
 * <p>번호가 아니라 이름으로 식별하며 append-only 로 관리한다. 새 정책 대상 태그(디지털관광주민증·반값여행 등)는 그 정책의 실제 대상 지역을
 * 확보할 때 여기에 추가하고 region_tag 에 행을 시딩한다.
 */
public enum RegionTagType {

    /** 인구감소지역 (행안부 고시 89). 현재 전 지역이 해당하나, 향후 다른 유형 지역 추가 시 구분자가 된다. */
    POPULATION_DECLINE,

    /**
     * 지역사랑 휴가지원(반값여행) 대상 — 2026 상반기 시범사업 <b>16곳</b>.
     *
     * <p>89곳 전체가 아니다. 예전에는 이 정책이 {@link #POPULATION_DECLINE} 을 대상으로 둬서 안 되는 73곳에도
     * 뱃지가 나갔다. 사전 신청까지 필요한 혜택이라 사용자가 헛걸음했다.
     */
    REGIONAL_VOUCHER,

    /**
     * 숙박세일페스타 대상 — <b>비수도권</b> 인구감소지역 85곳.
     *
     * <p>89곳에서 수도권 4곳(인천 강화·옹진, 경기 가평·연천)을 뺀 값이다. 서울에서 가까워 코스에 자주 뽑히는
     * 지역들이라, 안 걸러내면 눈에 잘 띄는 자리에서 거짓 뱃지가 난다.
     */
    STAY_FESTA,

    /**
     * 디지털관광주민증 참여 지자체 — 우리 89곳 중 <b>52곳</b>.
     *
     * <p>예전에는 이 정책이 {@link #POPULATION_DECLINE} 을 대상으로 둬서 <b>89곳 전부에 뱃지가 나갈</b>
     * 뻔했다. 실제로는 참여하지 않는 37곳이 있고, 그곳 사용자는 발급받아도 쓸 데가 없다.
     *
     * <p>확보가 늦었던 이유는 공식 페이지가 참여 지역을 목록이 아니라 지도로만 보여줘서였다. 명단을
     * 얻은 뒤 우리 89곳과 대조하니 <b>하나도 안 새고 전부 일치</b>했다(#498).
     */
    DIGITAL_TOURIST_CARD,

    /**
     * 동해선 관광패스 대상 — 우리 89곳 중 <b>3곳</b>(영덕·울릉·울진).
     *
     * <p>안내는 경주·포항까지 다섯을 말하지만 그 둘은 인구감소지역이 아니라 우리 목록 밖이다.
     */
    DONGHAE_RAIL_PASS,

    /**
     * 강원 해양치유·요트체험 할인 대상 — 우리 89곳 중 <b>3곳</b>(고성·삼척·양양).
     *
     * <p>주최가 말하는 대상은 동해안 6개 시군(강릉·속초·동해·삼척·고성·양양)인데 앞의 셋은 우리
     * 목록 밖이다. <b>고성군은 강원 쪽이다</b> — 경남에도 같은 이름이 있어 시도까지 맞춰야 한다.
     */
    GANGWON_MARINE_HEALING,

    /**
     * 충남 트래블 페스타 대상 — 우리 89곳 중 <b>9곳</b>(충남 전부).
     *
     * <p>주최는 충남 15개 시군 전체를 대상으로 두는데, 그중 우리 목록에 있는 것이 9곳이라 결과적으로
     * 우리 충남 전부다.
     */
    CHUNGNAM_TRAVEL_FESTA,

    /**
     * 반하다! 경북 대상 — 우리 89곳 중 <b>9곳</b>.
     *
     * <p>주최는 <b>역</b> 단위(경북 42개역)로 말한다. 그것을 시군으로 옮긴 뒤 우리 목록과 교차한
     * 결과다 — 김천·경주·경산·구미·칠곡·포항에도 역이 있지만 인구감소지역이 아니다.
     */
    GYEONGBUK_RAIL_REFUND
}
