package com.offway.core.policy.domain;

/**
 * 혜택을 <b>어디서 쓰는가</b> — 정책 도메인이 아는 만큼의 대상 분류(#140).
 *
 * <p>코스의 슬롯 종류가 아니라 <b>프로그램의 성질</b>이다. 숙박세일페스타가 숙소에서 쓰는 혜택이라는 건
 * 프로그램 약관이 정하는 사실이고, 그게 코스의 어느 자리에 붙는지는 코스가 정한다. 정책이 슬롯을 알면
 * {@code policy → itinerary} 역방향 의존이 생겨 두 도메인이 서로를 참조하게 된다.
 *
 * <p><b>단정할 수 있는 것만 넣는다.</b> 지금은 하나뿐이다 — 나머지 혜택은 가맹점·제휴처 목록이 있어야
 * 쓸 수 있는 자리를 알 수 있는데 우리에겐 그 데이터가 없다.
 */
public enum BenefitScope {

    /** 숙소 — 숙박세일페스타처럼 잠자리 값에 붙는 혜택. */
    LODGING
}
