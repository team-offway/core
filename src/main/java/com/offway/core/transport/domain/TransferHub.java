package com.offway.core.transport.domain;

import com.offway.core.common.geo.Coordinate;

/**
 * 갈아탈 만한 큰 터미널(#508) — <b>직통이 없을 때만</b> 여기를 거쳐 가는 길을 찾는다.
 *
 * <h2>왜 필요했나</h2>
 *
 * <p>예전에는 한 구간만 답했다. 그 구간에 차가 없어도 그렇게 답했다 — 서울에서 봉화까지 고속버스로 가라는
 * 안내가 나갔는데 봉화행 노선은 어디에도 없다. <b>없는 길을 안내하는 것은 아무 안내도 안 하는 것보다
 * 나쁘다.</b>
 *
 * <h2>왜 좌표로 두나</h2>
 *
 * <p>코드로 두면 수단마다 다른 값을 들어야 한다 — 고속은 {@code NAEK...}, 시외는 {@code NAI...} 로 코드
 * 공간이 갈려 있고, 같은 터미널인데 코드가 여럿인 경우도 있다(#507). 좌표 하나를 두고 수단별로 그 자리의
 * 터미널을 풀면 그 사정이 전부 흡수된다.
 *
 * <h2>고른 근거 (실측 2026-09-08)</h2>
 *
 * <p>89곳을 서울 출발로 전수 조회해, 직통이 없는 곳이 어느 허브를 거치면 닿는지를 봤다. 여기 있는 곳들이
 * 실제로 그 답으로 나온 터미널이다 — 예를 들어 무주는 대전복합, 단양은 청주, 곡성·고령은 광주를 거친다.
 *
 * <p>결과: 89곳 중 직통 76곳 · <b>경유로 새로 닿는 8곳</b> · 버스로 못 가는 5곳.
 *
 * <p><b>많이 넣을수록 좋은 것이 아니다.</b> 허브 하나마다 두 구간을 DB 에서 확인하므로 조회가 늘고,
 * 노선이 몰리지 않는 터미널은 답이 될 일이 거의 없다. 실측에서 답으로 나온 것과 전국 주요 환승지만 둔다.
 *
 * <p>좌표는 우리 터미널 마스터의 값이다(고속 코드 기준, 시외도 같은 자리에 있다).
 */
public enum TransferHub {

    SEOUL_GYEONGBU("서울경부", 37.50619217, 127.00745096),
    SEOUL_CENTRAL("센트럴시티(서울)", 37.50503994, 127.00425246),
    DONG_SEOUL("동서울", 37.53460761, 127.09418832),
    SEONGNAM("성남", 37.41312486, 127.12741533),
    CHEONAN("천안", 36.81973608, 127.15633919),
    CHEONGJU("청주", 36.62533754, 127.43170159),
    DAEJEON("대전복합", 36.35032438, 127.43674997),
    WONJU("원주", 37.34491889, 127.93071661),
    JEONJU("전주", 35.83437999, 127.13267242),
    GWANGJU("광주(유·스퀘어)", 35.16040761, 126.8793125),
    MOKPO("목포", 34.81274206, 126.41782065),
    SUNCHEON("순천", 34.94759306, 127.49136191),
    DAEGU("동대구", 35.87798596, 128.6303085),
    JINJU("진주", 35.178698, 128.09300646),
    BUSAN("부산", 35.28477323, 129.09547241);

    private final String label;
    private final Coordinate coordinate;

    TransferHub(String label, double lat, double lng) {
        this.label = label;
        this.coordinate = new Coordinate(lat, lng);
    }

    public String label() {
        return label;
    }

    public Coordinate coordinate() {
        return coordinate;
    }
}
