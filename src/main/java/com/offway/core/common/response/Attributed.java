package com.offway.core.common.response;

import java.util.Set;

/**
 * 출처를 <b>표기해야 하는</b> 기관을 스스로 밝히는 응답 DTO(#399).
 *
 * <p>{@code PageResponse.Paged} 와 같은 접점이다 — DTO 가 구현하면 래퍼가 집어간다. 그래서 컨트롤러는
 * 한 줄도 바뀌지 않는다.
 *
 * <h2>왜 DTO 가 선언하나 — 자동 추적이 아니라</h2>
 *
 * <p>호출 기록({@code CallerContext})으로 자동으로 모으면 <b>실호출만 잡힌다.</b> 우리가 가장 많이 쓰는
 * 경로가 정확히 그 반대다 — {@code poi_intro}·{@code festival_period}·{@code region_content} 처럼
 * <b>DB 에 담아 둔 공사 데이터</b>는 그 요청에서 외부를 부르지 않으므로 통째로 빠진다. 표기가 빠지는 것은
 * 규정 위반이라 "가끔 빠진다" 가 허용되지 않는다.
 *
 * <p>선언은 캐시 여부와 무관하게 맞다. 대신 <b>필드를 더하면서 선언 갱신을 깜빡할 수 있다</b> — 그건
 * 정규식으로 못 거르는 판단이라 훅이 아니라 테스트가 잡는다.
 *
 * <h2>응답 단위다 — 항목 단위가 아니다</h2>
 *
 * <p>표기 의무는 "이 화면에 어느 기관 데이터가 쓰였나" 이지 카드마다 라벨을 붙이라는 것이 아니다.
 * 항목 단위는 오히려 <b>더 나쁘다</b> — 인허가 식당 카드에 사진만 공사 것인데 그 카드에 {@code KTO} 가
 * 붙으면, 규정이 막으려는 오인("공사가 직접 운영하는 서비스처럼 보이게 하는 것")을 키운다.
 */
public interface Attributed {

    /**
     * 이 응답이 값을 빌려온 기관 중 <b>표기 대상</b>. 빈 집합이면 표기할 것이 없다.
     *
     * <p>실제로 그 값이 있을 때만 담는다 — 사진이 null 인 카드에 {@code KTO} 를 붙이면 안 쓴 출처를
     * 표기하게 된다.
     *
     * <p>교통(TMAP·TAGO·코레일)은 값을 대주더라도 담지 않는다. 이유는 {@link DataSource} 에 있다.
     */
    Set<DataSource> sources();
}
