package com.offway.core.common.response;

/**
 * 이 응답에 값을 대준 <b>기관</b>(#399) — 공모전 출처 표기 의무가 읽는 값이다.
 *
 * <p>표기 규정은 기관명을 요구한다.
 *
 * <blockquote>
 * {@code [O]} 출처: ⓒ한국관광공사 / {@code [X]} TourAPI (API 서비스명만 단독 표기 지양)
 * </blockquote>
 *
 * <p>그래서 {@code ExternalApi} 와 다르다. 그쪽은 <b>어느 API 를 몇 번 불렀나</b>(한도·사용량)를 세는
 * 값이라 국문관광정보·사진갤러리·관광빅데이터가 따로 있지만, 표기에서는 셋 다 한국관광공사 하나다.
 *
 * <p><b>문구는 여기 없다.</b> 서버가 {@code "출처: ⓒ한국관광공사"} 를 만들면 문구 소유가 서버로 넘어와
 * 다국어·디자인 변경이 배포 사안이 된다. 앱이 이 이름을 문구로 옮긴다.
 */
public enum DataSource {

    /** 한국관광공사 — 국문관광정보 · 관광빅데이터 · 사진갤러리 · 대한민국 구석구석 캐치프레이즈. */
    KTO,

    /** 지방행정인허가데이터개방 — 식당·숙소 등 인허가 장소. */
    LOCAL_PERMIT,

    /** 국가유산청 — 국가유산 정보. */
    KHS,

    /** 기상청 — 단기·중기 예보와 평년값. */
    KMA,

    /** 한국천문연구원 — 특일정보(공휴일). */
    KASI
}
