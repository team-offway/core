package com.offway.core.common.batch.domain;

/**
 * 손으로 돌릴 수 있는 배치(#537).
 *
 * <h2>왜 필요했나</h2>
 *
 * <p>배치를 고쳐도 <b>다음 주기까지 결과를 못 본다.</b> 주 1회짜리는 엿새를 기다려야 하는데, 그동안
 * 고친 것이 실제로 도는지 알 방법이 없다 — 실제로 교통 거점 사진 배치가 그랬다(#535). 로그도
 * 컨테이너가 바뀌면 사라져, 다음 회차를 놓치면 또 일주일이다.
 *
 * <h2>이름을 여기서 든다</h2>
 *
 * <p>이름과 실행을 <b>한 자리에</b> 둔다. 이름은 {@code batch_run} 의 키이자 관리자 화면이 마지막
 * 실행 시각을 붙이는 키다 — 등록하는 곳과 기록하는 곳이 갈리면 <b>조용히 어긋나</b> 목록에는 있는데
 * 시각이 영영 안 붙는다.
 *
 * <h2>무엇을 여기 넣지 않나</h2>
 *
 * <p><b>사용자에게 나가는 알림 배치는 넣지 않는다</b> — 여행 전후 알림·정책 알림이다. 손으로 돌리면
 * 진짜 푸시가 진짜 사용자에게 간다. 되돌릴 수 없는 것을 버튼 하나 뒤에 두지 않는다.
 */
public interface ManualBatch {

    /**
     * 배치 이름 — {@code batch_run.name} 과 <b>같은 값</b>이어야 한다.
     *
     * <p>다르면 관리자 목록에 이름은 뜨는데 마지막 실행 시각이 안 붙는다.
     */
    String batchName();

    /**
     * 지금 돌린다.
     *
     * <p><b>배치 자신의 가드는 그대로 탄다.</b> "오늘 이미 돌았으면 건너뛴다"·"받아 둔 것은 다시 안
     * 묻는다" 같은 규칙은 손으로 부를 때도 지켜야 한다 — 그것이 외부 한도를 지키는 장치다.
     * 그래서 눌러도 아무 일이 없을 수 있고, 그건 정상이다.
     */
    void runNow();
}
