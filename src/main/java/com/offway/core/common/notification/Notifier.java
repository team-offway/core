package com.offway.core.common.notification;

/**
 * 팀에게 한 줄 알린다 — 사람이 손을 써야 하는 일이 생겼을 때.
 *
 * <p><b>단방향이다.</b> 우리는 보내기만 하고 읽지 않는다. 그래서 구현이 디스코드 <b>웹훅</b>이지 봇이
 * 아니다 — 봇은 게이트웨이 연결·토큰·권한이 따라붙는데 우리가 얻는 것이 없다.
 *
 * <p><b>보내기 실패가 기능을 막지 않는다.</b> 알림은 관측이지 기능이 아니다. 구현은 예외를 밖으로
 * 던지지 않고, 대신 <b>왜 못 보냈는지를 로그에 남긴다</b> — 알림이 조용히 죽으면 알림이 없는 것과 같다.
 *
 * <p><b>호출자를 기다리게 하지 않는다.</b> 요청 경로(코스 생성 등)에서 불릴 수 있으므로 구현은 전송을
 * 비동기로 던지고 곧바로 돌아온다.
 */
public interface Notifier {

    /**
     * 메시지 한 줄을 보낸다.
     *
     * @param message 사람이 읽을 문구. 내부 식별자·시크릿을 담지 않는다
     */
    void send(String message);
}
