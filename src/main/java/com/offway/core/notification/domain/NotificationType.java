package com.offway.core.notification.domain;

/**
 * 알림 종류 — <b>앱이 아이콘·문구를 맞추는 키</b>(#263).
 *
 * <p><b>문구를 서버가 들지 않는다.</b> 프론트가 "어떤 값들이 오는지 정해 주시면 앱에서 아이콘·문구를
 * 맞추겠다" 고 했고, 실제로 문구는 화면 폭·서체·강조에 묶여 있어 앱이 쥐는 편이 낫다. 응답에는 이 상수
 * 이름만 실린다 — {@code OpeningStatus} 와 같은 방식이다.
 *
 * <p><b>상수가 하나뿐인 것은 미완성이 아니라 의도다.</b> 지금 서버가 실제로 만들 근거가 있는 알림은
 * 여행 전날 하나다. 보낼 사람이 없는 종류를 미리 나열하면 앱이 그 값을 기다리는 분기를 만들고, 영영
 * 오지 않는 분기가 남는다. 값이 느는 것은 클라이언트에 안전한 변경(추가)이므로 보낼 것이 생길 때 더한다.
 *
 * <p>추가 기준: <b>서버가 그 사실을 이미 알고 있고, 그것을 알릴 주체가 이 레포에 있는가.</b>
 */
public enum NotificationType {

    /**
     * 내일 여행을 떠난다 — 저장한 코스의 여행 시작일이 내일이다.
     *
     * <p>서버가 여행 날짜를 들고 있어 판단에 외부가 필요 없고, 알림을 받는 시점(전날)이 사용자가 할 일
     * (짐 싸기)과 맞는다.
     */
    TRIP_TOMORROW
}
