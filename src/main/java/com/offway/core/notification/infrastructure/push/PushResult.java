package com.offway.core.notification.infrastructure.push;

/**
 * 푸시 한 건의 결과(#270).
 *
 * <p><b>실패를 하나로 뭉치지 않는다.</b> "토큰이 죽었다" 와 "지금 못 보냈다" 는 대응이 정반대다 — 전자는
 * 행을 지워야 하고(계속 두면 매번 실패한다), 후자는 지우면 안 된다(다음에 성공할 토큰을 잃는다).
 * 그 구분을 문자열 비교로 호출부마다 하면 한 곳만 놓쳐도 멀쩡한 토큰이 사라진다.
 */
public enum PushResult {

    /** 보냈다. */
    SENT,

    /**
     * 이 토큰은 더 이상 유효하지 않다 — 앱이 지워졌거나 재설치됐다.
     *
     * <p>FCM 이 {@code UNREGISTERED}(또는 그에 준하는 응답)로 답한 경우다. 계속 두면 발송할 때마다
     * 실패하므로 행을 지운다.
     */
    UNREGISTERED,

    /** 이번에는 못 보냈다 — 네트워크·일시 오류. 토큰은 살아 있을 수 있으므로 지우지 않는다. */
    FAILED,

    /** 보낼 수단이 없다 — 서비스 계정 키가 없어 발송이 비활성이다. 실패로 세지 않는다. */
    DISABLED
}
