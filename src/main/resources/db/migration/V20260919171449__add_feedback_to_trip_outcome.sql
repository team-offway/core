-- 여행 후 모달의 여행지 평가를 담는다 — 지자체 전달용 피드백(#592).
--
-- **왜 이 표인가.** 알맹이가 같다 — (사용자, 코스) 하나에 답 하나이고, 모달에서 한 번에 들어온다.
-- 그리고 **탈퇴 삭제가 따라온다**: `CoursePurgeOnUserWithdrawn` 이 이미 이 표를 userId 로 지운다.
-- 별도 표를 만들면 purge 리스너를 새로 써야 하고, 그걸 빠뜨리면 주인 없는 사용자 입력이 남는다 —
-- 자유 텍스트는 개인정보 삭제 요구가 닿는 값이다.
--
-- 나중에 평가만의 생명주기가 필요해지면(답한 뒤 코멘트 추가·수정) 그때 분리한다.
--
-- **둘 다 NULL 을 허용한다.** 건너뛰기가 정상 상태다 — 모달의 본업은 연차 차감이라, 평가가 그것을
-- 막으면 확인만 하려던 사용자가 갇힌다. 그래서 기존 행도 그대로 유효하다(순서 무관·additive).
--
-- 길이 상한 200 은 `TripFeedback.MAX_COMMENT_LENGTH` 와 같아야 한다. 상한이 없으면 요청 하나의
-- 크기를 사용자가 정하고, 이 값은 사람이 읽어 지자체에 넘길 분량이어야 한다.

ALTER TABLE trip_outcome ADD COLUMN rating TINYINT;
ALTER TABLE trip_outcome ADD COLUMN comment VARCHAR(200);
