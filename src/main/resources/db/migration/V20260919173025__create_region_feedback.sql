-- 여행 후 모달에서 받은 여행지 평가 — **익명**으로 쌓는다(#592).
--
-- ## 왜 별도 표이고, 왜 아무 참조도 없나
--
-- 이 값은 **지자체에 전달된다.** 그러려면 개인을 특정할 수 없어야 한다.
--
-- 처음에는 `trip_outcome` 에 컬럼 둘을 더했다. 알맹이가 같고 탈퇴 삭제가 따라온다는 이유였는데,
-- **그 표는 `user_id` 를 들고 있어 평가가 사람에 직접 묶인다.** 익명이 되려면 그 연결이 없어야 하고,
-- 그러면 "탈퇴 시 함께 지워진다" 는 장점도 성립하지 않는다 — 지울 것이 애초에 없다.
--
-- **`course_id` 도 담지 않는다.** 코스는 `user_id` 를 들고 있어, 코스 참조만 남겨도 한 번의 조인으로
-- 사람이 특정된다. 별도 표로 옮기는 것만으로는 익명이 되지 않는다.
--
-- ## 왜 날짜가 아니라 연-월인가
--
-- `정선군 + 2026-09-19 + 특징적인 코멘트` 는 소규모 지역에서 좁혀질 수 있다. 우리가 다루는 곳이
-- 인구감소지역이라 지역별 표본이 작다는 점이 특히 그렇다.
--
-- 집계는 월·분기 단위다("2026년 9월 정선 만족도"). 날짜까지 남길 이유가 없으므로 버린다 —
-- **재식별 단서를 남기지 않는 것이 공짜일 때는 남기지 않는다.**
--
-- 여행 일수·이동수단 같은 맥락도 담지 않는다. 지역 개선에 쓸 만해 보이지만
-- `지역 + 시기 + 일수 + 수단` 조합이면 그 지역에 그렇게 간 사람이 한 명일 수 있다. 필요해지면
-- 그때 재식별 위험을 따져 더한다.
--
-- ## 중복은 누가 막나
--
-- 여기에 유니크 제약을 걸 수 없다(막을 키가 없다). `trip_outcome` 이 코스당 한 번만 답을 받으므로
-- 평가도 한 번만 들어온다 — 두 표를 한 트랜잭션에 쓰는 것이 그 보장을 잇는 조건이다.

CREATE TABLE region_feedback (
    id           BIGINT      NOT NULL AUTO_INCREMENT,
    -- 어느 지역에 대한 평가인가. 지역 마스터는 애그리거트 밖이라 raw ID 다(persistence-convention).
    region_id    BIGINT      NOT NULL,
    -- 1~5. 별점 없이 글만 남길 수 있어 NULL 을 허용한다.
    rating       TINYINT,
    -- 남기고 싶은 말. 별점만 남길 수 있어 NULL 을 허용한다. 길이는 TripFeedback.MAX_COMMENT_LENGTH.
    comment      VARCHAR(200),
    -- 받은 시기(YYYY-MM). 사전순 비교가 곧 시간순이라 범위 조회가 그대로 된다.
    submitted_ym CHAR(7)     NOT NULL,
    PRIMARY KEY (id)
);

-- 집계는 "이 지역의 이 기간" 을 묻는다.
CREATE INDEX idx_region_feedback_region_ym ON region_feedback (region_id, submitted_ym);
