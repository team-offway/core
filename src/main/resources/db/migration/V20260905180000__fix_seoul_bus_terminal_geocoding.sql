-- 서울권 시외버스 터미널 좌표 보정 (V20260805070449 시드) — #436.
--
-- 시드가 터미널 이름으로 좌표를 붙이면서 서울권 세 곳이 엉뚱한 자리에 놓였다. 고속 시드
-- (V20260805062008)에는 같은 터미널이 제자리 좌표로 들어 있어, 두 시드가 서로 다른 곳을 가리키고
-- 있었다.
--
-- 왜 심각한가 — 터미널 해석은 좌표 최근접이다(BusTerminalResolver, 반경 30㎞). 김포공항이 서울역에서
-- 0.2㎞ 떨어진 자리에 놓이는 바람에, **서울에서 출발하는 모든 시외버스 코스의 출발 터미널이
-- 김포공항으로 잡혔다.** 89곳 전수 실측에서 시외버스가 대표인 30곳이 전부 그랬고, 존재하지 않는
-- 구간("김포공항 → 합천")을 조회하니 구간 소요시간도 출발 시각도 30곳 전부 비었다(#443).
--
-- 좌표는 고속 시드의 같은 터미널 값을 쓴다. 세 곳 모두 고속·시외를 한 건물에서 취급하는 단일
-- 터미널임을 위키백과 소재지 주소로 확인했다.
-- forward-only — 시드 파일을 고치지 않고 code(UNIQUE) 기준 UPDATE 로 되돌린다.

-- 동서울: 마포·공덕 방면(37.55,126.92)으로 잘못 매핑 → 실제는 광진구 강변역로 50(구의3동).
-- 고속 12홈·시외 36홈을 한 건물에서 쓴다.
UPDATE bus_terminal SET lat = 37.53393134, lng = 127.09476219 WHERE code = 'NAI0511601';

-- 김포공항: 사실상 서울역 좌표(37.554,126.972)로 잘못 매핑 → 실제는 강서구 김포공항.
-- 서울 출발 시외버스 30곳을 전부 여기로 끌어당기던 자리다.
UPDATE bus_terminal SET lat = 37.55994673, lng = 126.80279331 WHERE code = 'NAI0750501';
UPDATE bus_terminal SET lat = 37.55994673, lng = 126.80279331 WHERE code = 'NAI0750503';

-- 서울남부: 종로·서대문 방면(37.573,126.973)으로 잘못 매핑 → 실제는 서초구 효령로 292(서초동).
-- 김포공항을 고치면 그다음으로 서울 출발을 끌어당길 자리라 함께 바로잡는다.
UPDATE bus_terminal SET lat = 37.48473869, lng = 127.01618622 WHERE code = 'NAI0671801';
