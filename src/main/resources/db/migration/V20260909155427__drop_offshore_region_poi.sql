--
-- 관광 API 가 남중국해 좌표를 준다. 담양호가 (19.69, 117.99) 로 와서 코스 이동시간이 2,918분
-- (48.6시간)으로 나갔고, 지도 핀은 필리핀 서쪽 바다에 찍혔다. 그 뒤 칸도 거기서 돌아오는 것으로
-- 계산돼 동선이 통째로 틀어진다.
--
-- 실측(2026-09-09 운영): region_poi 6,218건 중 10건. 그중 아홉이 토씨 하나 안 틀리고 같은
-- (19.69442748, 117.9925662504) 이고, 나머지 하나가 (0, 0) 이다. 인허가·국가유산·야영장은 0건이다.
--
-- **적재 검증과 같은 배포에 실려야 뜻이 있다.** 배치가 월 1회 다시 채우므로, 여기서만 지우면
-- 다음 회차에 그대로 돌아온다. 범위와 그 근거는 ServiceArea 가 소유한다.
--
-- 지우는 쪽을 고른 이유는 좌표가 이 테이블의 존재 이유이기 때문이다 — region_poi 는 코스 후보를
-- 담고, 좌표 없는 후보는 동선에 못 올린다. 배치가 올바른 좌표로 다시 받아 오면 그때 복구된다.
DELETE FROM region_poi
WHERE lat IS NULL
   OR lng IS NULL
   OR lat < 32.5
   OR lat > 39.0
   OR lng < 124.0
   OR lng > 132.5;
