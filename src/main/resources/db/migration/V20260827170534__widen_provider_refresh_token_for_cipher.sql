-- provider 갱신 토큰을 암호화해 저장하면서 컬럼을 넓힌다 (#301).
--
-- ## 왜 넓혀야 하나
--
-- 저장 형태가 `v1:base64(iv‖ciphertext‖tag)` 다. IV 12바이트·GCM 태그 16바이트가 붙고 base64 가
-- 4/3 배로 부풀린다. 계산하면 이렇다.
--
--   평문 100자 → 175자
--   평문 200자 → 307자
--   평문 300자 → 443자
--   평문 512자 → 723자   ← 지금 컬럼(512)을 넘긴다
--
-- Apple 의 refresh 토큰은 실제로 100자 안팎이라 지금 값으로도 들어가지만, 컬럼 폭이 평문 기준으로
-- 잡혀 있는 채 두면 provider 가 토큰을 길게 바꾸는 순간 저장이 깨진다. 그때 나는 것은 예외가 아니라
-- **연결 해제만 조용히 안 되는 상태**다 — 저장 실패가 로그인을 깨뜨리지 않게 삼키기 때문이다.
--
-- 1024 는 평문 700자까지 담는다. VARCHAR 는 실제 길이만큼만 쓰므로 넓혀 두는 비용이 없다.
--
-- ## 기존 행
--
-- 없다. 2026-08-25 소유 키 전환(#280) 때 user_identity 를 비웠다. 그래서 평문→암호문 backfill 이
-- 필요 없고, 이 시점이 이 전환의 가장 싼 자리다.

ALTER TABLE user_identity
    MODIFY COLUMN provider_refresh_token VARCHAR(1024) NULL
        COMMENT 'provider 가 준 갱신 토큰을 암호화한 값(#301). v1:base64(iv‖ct‖tag). 없으면 해제 불가';
