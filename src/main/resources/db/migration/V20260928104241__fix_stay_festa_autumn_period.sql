-- 숙박세일페스타 기간을 가을분으로 옮긴다(#612).
--
-- **왜 필요한가.** 시드(`V20260901184241`)가 여름분 기간(2026-06-11 ~ 08-31)으로 들어갔다. 8/31 에
-- 끝났으므로 그 뒤로 코스를 만들면 `isActiveOn` 이 거짓이 되어 **숙박 혜택 뱃지가 안 붙는다.** 그런데
-- 사업은 계속 돌고 있다 — 같은 해에 여름분·가을분이 따로 열리는 구조다.
--
-- 그 시드는 이미 적용됐으므로 고치지 않고(checksum) 새 timestamp 로 보정한다.
--
-- ## 확인한 값 (2026-09-28)
--
--   가을분 기간   2026-09-22 ~ 2026-11-08
--   할인 규모     1박  7만원↑ 3만원 / 7만원↓ 2만원
--                 2박↑ 14만원↑ 7만원 / 14만원↓ 5만원
--   대상         비수도권 인구감소지역 85개 기초지자체 · 성인 1인 1매
--   발급         매일 오전 10시 선착순 · 약 8만 장
--
-- **금액·조건·apply_url 은 건드리지 않는다.** 시드 값이 그대로 맞고, 링크(ktostay.visitkorea.or.kr)도
-- 실제 호출로 200 을 확인했다. 틀린 것은 기간뿐이다.
--
-- ## 왜 id 가 아니라 type 으로 찾나
--
-- 시드가 id 를 명시(2)하지만 여기서는 분류 컬럼으로 고른다. 숙박세일페스타는 **분류당 한 건**이고,
-- id 는 시드 순서라는 우연에 기대는 값이다. 나중에 백오피스에서 다시 만들어 id 가 달라져도 같은 행을
-- 가리키게 하려는 것이다.
--
-- **컬럼 이름은 `type` 이다.** 엔티티 필드가 `PolicyType type` 이고 `@Column` 으로 이름을 바꾸지 않아
-- DDL 도 `type` 이다(`V20260723220827__create_policy.sql`). `policy_type` 으로 적었다가 CI 의 마이그레이션
-- 검증이 1054(Unknown column)로 잡았다 — 이 검증이 있는 이유가 그것이다.
--
-- ## checked_on 을 같이 올린다
--
-- `PolicyStaleness` 가 이 날짜로 "언제 확인한 값인가" 를 판단한다. 기간만 고치고 날짜를 두면 방금 확인한
-- 값이 오래된 것으로 잡힌다.

UPDATE policy
SET period_start = '2026-09-22',
    period_end   = '2026-11-08',
    period_note  = '매일 오전 10시 선착순 발급 · 가을분(여름분은 8/31 종료)',
    verified     = TRUE,
    checked_on   = '2026-09-28'
WHERE type = 'STAY_FESTA';
