-- 이 파일은 더 이상 데이터를 넣지 않는다 (#344).
--
-- ## 무엇이 있었나
--
-- 여기에 `DELETE FROM policy;` 로 전량을 지우고 세 행을 다시 넣는 스크립트가 있었다. 정책이 런타임
-- write 없는 레퍼런스 데이터일 때는 그것이 옳았다 — 파일이 곧 정본이라 idempotent 가 자연스러웠다.
--
-- ## 왜 비웠나
--
-- **백오피스가 정책을 고칠 수 있게 되면서 그 전제가 깨졌다.** repeatable 은 체크섬이 바뀔 때마다 다시
-- 도는데, 어드민이 값을 고쳐 둔 상태에서 이 파일이 한 번 더 돌면 **편집분이 통째로 날아간다.** 그것도
-- 배포 한 번으로, 조용히.
--
-- ## 왜 지우지 않고 남겼나
--
-- `spring.flyway.validate-on-migrate` 가 기본 true 다. 적용 기록은 남았는데 파일이 없으면 부팅이 막힐
-- 수 있다. 그래서 **내용만 비우고 파일은 묘비로 남긴다** — 마지막 한 번은 빈 스크립트로 돌아 아무 일도
-- 하지 않는다. DELETE 가 없으므로 데이터는 그대로다.
--
-- 위 주석을 지우지 않은 이유는 **근거가 거기 있기 때문**이다. 어느 출처를 언제 확인해 이 값이 됐는지,
-- 무엇을 담고 무엇을 뺐는지(#217)는 백오피스 화면이 답해 주지 못한다.
--
