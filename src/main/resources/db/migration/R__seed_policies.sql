-- 말해 주지만 기계가 못 읽는다 — 낡음을 알아채는 알림이 읽는 것은 컬럼 쪽이다.
--
-- **행마다 확인일이 다르다.** 셋을 한 날짜로 뭉뚱그리면 알림이 낡음을 그만큼 늦게 잡는다. 값을 고칠 때
-- 주석과 컬럼을 함께 고친다 — 둘이 갈리면 사람이 읽는 것과 기계가 읽는 것이 달라진다.
