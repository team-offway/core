--
-- 울릉군은 버스로 갈 수 없다. 육지에서 130km 떨어진 섬이라 배가 유일한 수단이고,
-- 인구감소지역 89곳 중 버스로 못 닿는 유일한 곳이다.
--
-- 여객선터미널 목록(GetPsnshipTrminlList)이 아니라 항구 목록(GetPortList)을 쓴다.
-- 터미널 쪽은 27곳뿐인 데다 이름과 주소가 어긋난 행이 절반 가까이다 — 인천 터미널에 전남 여수 주소,
