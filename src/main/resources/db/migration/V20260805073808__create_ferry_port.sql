-- 항구 목록은 이름이 정확하고 울릉_도동·저동·사동까지 담는다.
--
-- 좌표는 결측 가능하다. 항구 목록도 좌표를 주지 않아 이름으로 지오코딩했고,
-- 실제 항구가 아닌 항목이 섞여 있어 전부 찾아지지는 않는다.
-- 이름 접두사가 시도명인 항구는 지오코딩된 시도와 대조해 검증했다 — 어긋난 행은 좌표를 비웠다
-- (#97 리뷰: `부산_태종대` 가 인천 좌표로 잡혀 있었다).
-- 실측(2026-08-06): 500곳 중 387곳 좌표 확보.

