-- ## 왜 지금인가
--
-- 이 정책은 존재가 확인됐는데도 verified=FALSE 로 눌려 있었다. 이유는 하나였다 — **참여 지자체
-- 명단을 확보하지 못해** 대상 태그가 POPULATION_DECLINE(89곳)이었고, 그대로 열면 참여하지 않는
-- 37곳에도 뱃지가 나간다. 발급받아도 쓸 데가 없는 지역이다.
--
-- 명단을 확보해 우리 89곳과 대조했고(52곳 일치), 전용 태그로 옮겼다
-- (R__seed_program_region_tags.sql · RegionTagType.DIGITAL_TOURIST_CARD).
-- 거짓 뱃지가 날 이유가 사라졌으므로 이제 연다.
--
-- ## 왜 시드 파일을 안 고치나
--
-- V20260901184241 은 이미 적용됐다. Flyway checksum 이 깨지므로 새 마이그레이션으로 보정한다.
--
-- ## 운영은 이미 TRUE 다
--
-- 어드민에서 먼저 바뀌어 있었다(실측 2026-09-07). 이 마이그레이션이 바꾸는 것은 **아직 그 손길이
-- 닿지 않은 환경**(로컬·테스트·새로 띄우는 인스턴스)이다. 운영에서는 같은 값을 다시 쓴다.
--
-- 기간·상세는 건드리지 않는다. 이 혜택은 상시 운영이라 종료일이 없고, 가맹점 수는 자주 바뀌어
-- 시드가 따라가기 어렵다 — 상세 문구는 어드민이 소유하는 편이 맞다.
UPDATE policy
   SET verified = TRUE,
       checked_on = '2026-09-07'
 WHERE type = 'DIGITAL_TOURIST_CARD';
