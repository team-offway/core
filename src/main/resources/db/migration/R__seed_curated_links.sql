-- 어드민이 붙은 뒤에도 그대로 뒀다면 **배포 한 번이 어드민이 넣고 고친 항목을 통째로 지웠을 것이다.**
-- #341 에서 이 자리에 그렇게 적어 두고 #342 에서 걷어냈다.
--
-- 담는 기준(#340): **우리가 데이터를 다 갖지 못해 웹뷰로 넘기는 것**. 여행자가 직접 신청해 받는 혜택은
-- policy 가 소유하므로 여기 중복해 넣지 않는다 — 홈에서 같은 것이 뱃지와 칩으로 두 번 보인다.
