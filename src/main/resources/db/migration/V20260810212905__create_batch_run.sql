-- 배치가 "오늘 이미 돌았는지" 를 남기는 표 — #226.
--
-- 왜 필요한가: 중심 관광지 적재는 "89곳이 전부 최신 달을 가졌는가" 로 건너뛸지 정했는데, 이 API 는
-- 지역마다 발행 시점이 달라 그 조건이 사실상 참이 되지 않았다. 그래서 부팅할 때마다 89회를 다시 쐈고,
-- 배포가 잦은 날에는 그만큼 곱해져 일일 한도를 태웠다.
--
--   15:24  갱신 완료 지역=50/89 기준월별={2026-06=3, 2026-07=47}
--   16:07  0/89 — 전부 TooManyRequests
--   16:13  0/89
--
-- 자기강화 고리다: 건너뛰기 실패 → 89콜 → 한도 소진 → 더 많은 실패 → 최신 달을 못 채움 → 또 실패.
--
-- **결과가 아니라 실행을 기록한다.** 적재 결과(hub_attraction 의 행)로 판정하면, 전부 실패한 날에는
-- 아무것도 안 써져서 다음 부팅이 또 89회를 쏜다 — 정확히 위 로그의 16:07·16:13 이다. 실행 시각을 따로
-- 남겨야 그 폭주가 멎는다.
--
-- 이름을 키로 두어 다른 배치도 같은 표를 쓴다(지역 콘텐츠 등).
--
-- FK 없음(영속성 규약).

CREATE TABLE batch_run (
    id          BIGINT      NOT NULL AUTO_INCREMENT,
    -- 배치 식별자. 코드의 상수와 짝이며, 바꾸면 그 배치는 "한 번도 안 돈 것" 이 된다.
    name        VARCHAR(100) NOT NULL,
    -- 마지막으로 **시작한** 시각(KST). 성공·실패를 가리지 않는다.
    last_run_at DATETIME     NOT NULL,
    PRIMARY KEY (id),
    -- 배치당 한 행.
    CONSTRAINT uk_batch_run_name UNIQUE (name)
);
