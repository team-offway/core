-- 정책을 마지막으로 사람이 확인한 날(#220).
--
-- 정책은 수동 seed 라 **낡는 것이 유일한 실패 모드**인데, 언제 확인한 값인지 모르면 낡았는지도 알 수 없다.
-- #217 이 출처와 확인일자를 각 행 주석으로 남겼지만 주석은 기계가 못 읽는다 — 알림이 읽으려면 데이터여야
-- 한다.
--
-- **출처 URL(source_url)은 만들지 않는다.** 지금 세 행의 출처가 전부 apply_url 과 같은 페이지라, 컬럼을
-- 더하면 같은 값이 두 칸에 생긴다. 둘이 갈리는 정책이 생기면 그때 나눈다.
--
-- 값은 R__seed_policies.sql 이 채운다. 그쪽이 정책 데이터의 정본이라 여기서 backfill 하면 진실이 둘이 된다.
ALTER TABLE policy
    ADD COLUMN checked_on DATE NULL COMMENT '사람이 마지막으로 출처를 확인한 날. 낡음 감지의 기준';
