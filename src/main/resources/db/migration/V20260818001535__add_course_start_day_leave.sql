-- 저장 코스가 "첫날에 쓴 연차" 를 기억한다 (#138).
--
-- 왜 필요한가: 상세 조회와 날짜 수정이 열차 접근을 다시 계산한다. 그때 출발 시각을 모르면
-- 생성은 반차(12시) 기준으로 짠 코스를 상세는 종일(08시) 기준으로 되짚는다 — 같은 코스가
-- 두 근거를 갖게 되고, 날짜를 옮기면 첫날 일정이 조용히 다시 늘어난다(#214 가 경고한 유형).
--
-- NULL 은 "이 컬럼이 생기기 전에 저장된 코스" 다. 그때 동작이 종일 기준이었으므로 읽는 쪽이
-- FULL_DAY 로 답한다 — 지어내지 않고 그 시절 결과를 그대로 유지한다.
ALTER TABLE course
    ADD COLUMN start_day_leave VARCHAR(20) NULL
        COMMENT '첫날에 쓴 연차(FULL_DAY·HALF_DAY·QUARTER_DAY). 이 컬럼 이전 코스는 NULL=FULL_DAY';
