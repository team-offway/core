-- 연차 사용 내역에 상세 메모를 더한다(#319).
--
-- 기존 reason(사유)과 별개다. 화면에 사유와 상세 메모 입력이 따로 있어, 한 칸에 몰면 둘 중 하나는
-- 담을 자리가 없어진다.
--
-- reason 보다 길게 잡는다 — 사유는 한 줄 라벨에 가깝고 메모는 사용자가 풀어 쓰는 자리다.
-- 인덱스가 걸리지 않는 칸이라 길이가 인덱스 키 상한에 영향을 주지 않는다.
--
-- ADD COLUMN 이라 순서 무관하고(out-of-order 안전), 기존 행은 NULL 로 남는다 — 메모가 없던 내역과
-- 사용자가 비워 둔 내역이 같은 값이 되는데, 둘을 가를 이유가 없다.
ALTER TABLE leave_usage
    ADD COLUMN memo VARCHAR(500) NULL;
