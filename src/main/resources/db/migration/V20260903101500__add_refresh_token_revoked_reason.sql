-- refresh 토큰을 왜 폐기했는지 남긴다(#389).
--
-- 회전 직후 유예 창 안에 같은 refresh 가 다시 오면 새 쌍을 다시 발급하는데(응답 유실 복구), 그 판정을
-- "방금 폐기됐나" 로만 하면 로그아웃도 방금 폐기한 것이라 통과한다 — 로그아웃 뒤 10초 동안 그 토큰으로
-- 세션을 되살릴 수 있게 된다. 탈취 감지로 전량 폐기한 직후도 마찬가지다.
--
-- 그래서 "회전으로 폐기된 것" 만 복구 대상으로 삼는다.
--
-- 기존 행은 NULL 로 남는다. 회전으로 폐기된 옛 행이 복구 대상에서 빠지는 방향이라 안전하고,
-- 유예 창이 10초라 백필할 값도 없다.
ALTER TABLE refresh_token
    ADD COLUMN revoked_reason VARCHAR(20) NULL COMMENT '폐기 사유 — ROTATED · LOGOUT · REUSE_DETECTED';
