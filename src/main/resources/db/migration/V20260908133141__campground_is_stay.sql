-- 야영장을 볼거리에서 숙박으로 옮긴다 (#516).
--
-- ## 무엇이 문제였나
--
-- 중간 관광지 자리에 캠핑장이 떴다. 인허가 분류가 야영장을 볼거리로 보고 있었기 때문이다.
--
--   CAMPGROUND(PlaceKind.SIGHT, "야영장", …)   ← 잘 곳이지 볼 곳이 아니다
--
-- 운영 실측(2026-09-08)에서 **인허가 볼거리 3,844건 중 2,360건(61%)이 야영장**이었다. 사찰·박물관
-- 같은 PREFERRED 가 1,006건뿐이라, 그것이 떨어지는 지역에서는 바로 야영장이 볼거리로 올라왔다.
--
-- ## 빼도 볼거리가 얇아지지 않는다
--
-- 관광 API + 국가유산 + 인허가를 89곳 전수로 셌다.
--
--   야영장 포함   지역당 평균 116 · 임계(18) 미만 1곳 · 최소 15
--   야영장 제외   지역당 평균  90 · 임계(18) 미만 1곳 · 최소 15   ← 미달 지역이 안 는다
--
-- 그 한 곳(대구 서구)은 야영장을 넣어도 15건이라 어차피 미달이었다. **야영장이 실제로 채워주던
-- 지역이 없다.**
--
-- ## 왜 마이그레이션이 필요한가
--
-- 장소 풀은 부팅 때 파일에서 적재하는데, **체크섬이 같으면 통째로 건너뛴다**(재배포마다 12만 건을
-- 다시 넣지 않으려는 규칙이다). 그래서 코드에서 분류를 고쳐도 이미 적재된 행은 그대로다.
--
-- 파일을 다시 만들지 않는 이유는 원본이 870MB 에 좌표계 변환까지 필요한 분기 갱신물이라서다.
-- 대신 읽는 쪽이 파일의 `kind` 칸 대신 **분류에서 종류를 얻게** 바꿨다(`PlacePoolCsvReader`) —
-- 두 값이 따로 실려 어긋난 것이 이 문제의 뿌리였다.
--
-- ## 숙박 쪽 영향
--
-- 인허가 숙박이 26,365 → 28,725건이 된다. 다만 숙박 보충은 후보가 둘 미만일 때만 돌고, 인허가에는
-- 사진이 없어 코스에서 뽑히는 일은 드물다.

-- ## 이중 등록을 먼저 걷어낸다
--
-- `ux_licensed_place_natural (region_id, kind, name, address)` 가 걸려 있어, 그냥 UPDATE 하면
-- **1062 Duplicate entry 로 죽는다** — 마이그레이션 실패라 부팅이 안 된다.
--
-- 원인은 원본 데이터다. 한 업소가 **야영장업과 숙박업으로 각각 신고**된 경우가 있어, 종류를 합치면
-- 자연키가 겹친다(운영 실측 36건 — 남해에덴캠핑장·캠핑소리251·아름채 등).
--
-- 겹치는 쪽은 **야영장 행을 지운다.** 남는 숙박 행이 같은 장소를 이미 가리키고, 그쪽 분류가 더
-- 구체적인 업종(숙박업·펜션 등)이라 화면에 나갈 뱃지로도 낫다.
DELETE c
  FROM licensed_place c
  JOIN licensed_place s
    ON s.region_id = c.region_id
   AND s.name = c.name
   AND s.address = c.address
   AND s.kind = 'STAY'
 WHERE c.category = 'CAMPGROUND'
   AND c.kind = 'SIGHT';

UPDATE licensed_place
   SET kind = 'STAY'
 WHERE category = 'CAMPGROUND'
   AND kind = 'SIGHT';
