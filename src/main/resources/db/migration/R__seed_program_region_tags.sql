-- 숙박세일페스타 — 비수도권 인구감소지역 85곳.
--
-- 85곳 명단을 박지 않고 수도권을 빼서 도출한다. 명단을 적으면 89곳 시드와 두 벌이 되어 언젠가 어긋나고,
-- 숫자 85 가 어디서 나온 값인지도 코드에서 사라진다. 이렇게 두면 지역 시드가 바뀔 때 함께 따라간다.
-- (우리 89곳의 수도권은 인천 강화군·옹진군, 경기 가평군·연천군 넷이다. 서울은 인구감소지역이 없다.)
INSERT INTO region_tag (region_id, tag)
SELECT id, 'STAY_FESTA'
  FROM region
 WHERE sido NOT IN ('서울특별시', '인천광역시', '경기도');
