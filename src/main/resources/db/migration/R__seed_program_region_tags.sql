-- 프로그램별 대상 지역 태그 (수동 적재 · repeatable).
--
-- POPULATION_DECLINE 은 여기서 다루지 않는다. 그건 행안부 고시라 89곳 전체가 고정이고
-- V20260723213322 이 이미 넣었다. 이 파일은 "정책 프로그램마다 다른 대상 지역" 만 소유한다.
--
-- repeatable 인 이유: 참여 지자체는 해마다 바뀐다(디지털관광주민증 44 → 52, 반값여행 시범 16곳).
-- versioned 로 두면 명단이 바뀔 때마다 보정 마이그레이션이 쌓이고, 지금 명단이 무엇인지 알려면
-- 파일 여러 개를 겹쳐 읽어야 한다. 정책 시드(R__seed_policies.sql)와 같은 성격이라 같은 방식을 쓴다.
--
-- 이 파일이 소유한 태그만 지우고 다시 넣는다. tag <> 'POPULATION_DECLINE' 로 쓸어내지 않는 이유는
-- 나중에 다른 성격의 태그가 생겼을 때 이 파일이 남의 것을 조용히 지우게 되기 때문이다.
DELETE FROM region_tag WHERE tag IN ('REGIONAL_VOUCHER', 'STAY_FESTA', 'DIGITAL_TOURIST_CARD');

