-- 코스 차감 내역이 "첫날 반차였는가" 를 스스로 기억한다(#170).
--
-- 저장 코스의 여행 날짜를 고치면 평일 수·공휴일이 달라져 차감량을 다시 계산해야 하는데, 그 계산에는
-- 처음 차감할 때 쓴 반차 여부가 필요하다. 지금까지 이 값은 요청에만 있고 아무 데도 남지 않았다.
--
-- 값에서 되짚을 수도 없다. days 의 소수점(.5)은 "반차였다" 와 대응하지 않는다 — 출발일이 주말·공휴일이면
-- 반차를 골라도 차감이 정수로 나온다. 그 코스를 평일로 옮기면 반차가 조용히 종일로 바뀌어 0.5 를 더 깎는다.
--
-- 수동 내역(course_id IS NULL)에는 해당이 없어 NULL 을 허용한다. 기존 코스 차감 행은 NULL 로 남는데,
-- 읽는 쪽이 NULL 을 "반차 아님" 으로 본다 — 이 컬럼이 없던 시절의 동작과 같다.
ALTER TABLE leave_usage
    ADD COLUMN half_day_start BOOLEAN NULL COMMENT '코스 차감 시 첫날 반차 여부. 수동 내역은 NULL';
