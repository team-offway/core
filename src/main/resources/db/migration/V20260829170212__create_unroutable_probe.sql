-- TMAP 이 좌표 탓으로 거절한 구간 기록 (#335).
--
-- ## 왜 필요한가
--
-- 도로에 안 붙는 좌표(귀목봉 · 해발 1,036m 산 정상)가 코스 슬롯으로 들어가면 TMAP 이 400 을 준다.
-- 그러면 코드가 폴백해 방문 순서와 이동시간이 **직선거리**로 떨어지는데, 코스는 200 으로 정상 응답한다.
-- 산을 직선으로 넘는 시간이 화면에 뜨고 사용자는 그게 틀린 값인지 알 방법이 없다.
--
-- 사전 검사는 못 한다 — 경로 API 는 일 1,000건이고 장소 풀은 12만 건이다. 그래서 **실패를 기억한다.**
--
-- ## 왜 장소(contentId)가 아니라 좌표인가
--
-- 문제는 장소가 아니라 좌표다. 인허가 풀은 **31.4%(38,136건)가 다른 장소와 좌표를 공유**하므로,
-- 좌표 기준으로 적으면 같은 자리의 다른 장소도 한 번에 걸러진다.
--
-- ## 왜 짝(partner)을 함께 적는가
--
-- A→B 가 거절돼도 A 가 문제인지 B 가 문제인지 응답만으로는 못 가른다. 진짜 못 푸는 좌표는 들어오는
-- 구간과 나가는 구간이 둘 다 실패하므로 **서로 다른 짝이 둘 이상** 쌓이고, 옆에 있었을 뿐인 멀쩡한
-- 좌표는 짝이 하나뿐이다. 판정이 "짝이 둘 이상" 한 줄로 끝나 한국어 메시지를 읽을 필요가 없다.
--
-- ## 크기 상한
--
-- 행이 느는 속도는 **실제 TMAP 거절 빈도**가 정한다(운영 로그 24시간 5건 → 구간당 2행이라 하루 10행 남짓,
-- 1년에 4천 행 규모). 같은 구간의 재실패는 UNIQUE 로 접히므로 한 좌표가 무한히 늘지 않는다.
--
-- ## 좌표를 DECIMAL 로 두는 이유
--
-- DOUBLE 을 키로 쓰면 마지막 자리가 한 번만 달라져도 다른 좌표가 되어, 차단해 둔 것이 다음 코스에서
-- 되살아난다. 소수 7자리(약 1cm)는 우리 좌표 출처가 주는 정밀도보다 이미 촘촘하다.
--
-- FK 는 두지 않는다(영속성 규약). 참조하는 대상도 없다 — 좌표는 어느 테이블의 행도 가리키지 않는다.

CREATE TABLE unroutable_probe (
    id          BIGINT        NOT NULL AUTO_INCREMENT,
    lat         DECIMAL(10,7) NOT NULL COMMENT '의심 좌표 위도',
    lng         DECIMAL(10,7) NOT NULL COMMENT '의심 좌표 경도',
    partner_lat DECIMAL(10,7) NOT NULL COMMENT '같은 구간 반대편 위도 — 이 값의 가짓수가 증거의 수다',
    partner_lng DECIMAL(10,7) NOT NULL COMMENT '같은 구간 반대편 경도',
    reason      VARCHAR(20)   NOT NULL COMMENT 'NO_ROAD_LINK(1100) · OUT_OF_BOUNDS(1009)',
    observed_at DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    -- 같은 구간의 재실패는 새 증거가 아니다. 세면 한 코스만 반복 생성해도 차단 조건이 채워진다.
    UNIQUE KEY uq_unroutable_probe_leg (lat, lng, partner_lat, partner_lng)
);

-- 조회는 언제나 "좌표별로 짝이 몇 개인가" 다. UNIQUE 의 앞 두 칸이 이미 그 순서라 별도 인덱스를 두지 않는다.
