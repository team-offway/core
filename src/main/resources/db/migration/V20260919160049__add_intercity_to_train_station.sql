-- 기차역에 간선 열차 정차 여부를 붙이고, 좌표가 틀린 역의 좌표를 비운다(#590).
--
-- **왜 필요한가.** 출발지 자동완성은 사용자가 **직접 고르는** 화면이다. 통근 전용 역이 목록에
-- 있으면 그것을 고른 사용자가 열차 없는 코스를 받는데, 그건 우리가 고를 수 있게 해 놓고
-- degrade 시킨 것이다. GPS 로 최근접을 자동 선택할 때와 성질이 다르다.
--
-- **목록으로는 못 가른다.** TAGO 의 도시별 역 목록에 노량진·신도림·서빙고가 그대로 들어 있다
-- (서울 12곳 실측). 그래서 운행 여부를 물어 쟀다.
--
-- ## 어떻게 쟀나 — 1,772콜, 두 라운드
--
-- 역마다 먼 허브로 편성을 물어 하나라도 있으면 간선역으로 본다(첫 히트에서 끊어 콜을 아꼈다).
--
--   1차  부산·목포·강릉·동대구 4곳                                    1,073콜 → 간선 170 / 미운행 171
--   2차  1차 미운행 171곳을 제천·청량리·순천·안동·서울 5곳으로 재확인      682콜 → 52곳이 살아남
--
-- **2차가 없었으면 목포역·전주역·원주역·남원역·정선역이 사라졌다.** 1차 허브가 간선 종착지뿐이라
-- 지선(정선선·전라선·중앙선)에서 출발하는 역이 전부 미운행으로 잡혔다. 전량 측정을 그대로 믿으면
-- 틀린 필터가 멀쩡한 데이터를 지운다.
--
-- 소비한 콜은 집계에 남겼다(`probe:train-intercity`) — `scripts/external/probe-notify.sh`.
--
-- ## 기본값이 TRUE 인 이유
--
-- 새로 들어오는 역은 재기 전까지 쓸 수 있어야 한다. 통근역으로 잘못 낮추면 멀쩡한 역이 목록에서
-- 사라지는데, 반대는 지금까지의 동작과 같을 뿐이다(bus_terminal.is_terminal 과 같은 판단).
--
-- ## 좌표가 틀린 역 — 비운다
--
-- TAGO 의 도시별 목록과 우리 시도 판정을 대조해(17콜) 어긋난 4곳을 찾았다. 이름으로 지오코딩하다
-- 동명이의에 걸린 것들이다.
--
--   신림 NAT021357  원주시 신림면인데 서울 관악구 신림동으로 잡혔다
--   대야 NAT320131  군산시 대야면인데 시흥 대야동으로
--   상동 NAT013747  밀양시 상동면인데 부천 상동으로
--   진성 NAT880825  진주시 진성면인데 전남으로
--
-- **새 좌표를 추측해 넣지 않는다.** 시드 마이그레이션이 정한 규칙 그대로다 — 틀린 좌표를 남기면
-- 최근접 탐색이 엉뚱한 곳을 답하고, 비우면 탐색에서 빠질 뿐이다. 코드는 실재하므로 구간 조회에는
