--
-- ## 왜 옮기나
--
-- repeatable seed 를 무효화하면 **새 DB(로컬·테스트)에 정책이 하나도 없게 된다.** 앱은 뱃지가 없는 채로
-- 뜨고, 정책 매칭 통합 테스트는 넣을 데이터가 없어진다.
--
-- 그래서 지금 세 행을 일회성으로 여기 박는다. 이 파일은 **다시 돌지 않으므로** 어드민이 고친 값을
-- 덮어쓸 수 없다 — repeatable 이 위험했던 지점이 정확히 그것이었다.
--
-- ## 운영에서는 아무 일도 일어나지 않는다
--
-- 세 행이 이미 같은 id 로 있다. ON DUPLICATE KEY UPDATE 로 no-op 을 명시해, 있으면 건드리지 않고
-- 없으면(새 DB) 넣는다. **UPDATE 절을 비워 둘 수 없어** id = id 로 아무것도 안 바꾸는 대입을 쓴다.
--
-- ## 값은 옮기는 시점의 것이다
--
-- 이 값들은 2026-08-28·08-10 에 확인한 것이고, 앞으로는 백오피스가 소유한다. **여기를 고쳐서 정책을
-- 바꾸지 않는다** — 적용된 마이그레이션은 다시 돌지 않으므로 고쳐도 반영되지 않고, 파일만 현재 상태와
-- 다른 말을 하게 된다. 값을 바꾸려면 백오피스에서 고친다.
