-- 연차 사용 내역의 **등록 시각**(#375).
--
-- 화면이 "방금 등록한 것" 에 New 칩을 24시간 띄우는데, 지금은 그걸 알 방법이 없다.
--
-- used_on 으로 대신할 수 없다. 그건 연차를 *쓴 날*이라 등록한 날과 다르다 — 지난주 월요일에 쓴 연차를
-- 오늘 등록하는 일이 흔하고, 그러면 방금 등록했는데도 칩이 안 뜬다. 반대로 미래 날짜로 미리 잡아 둔
-- 내역은 영영 "새 것" 으로 남는다. id 도 안 된다. 순서는 알아도 시각을 모른다.
--
-- **기존 행은 NULL 로 둔다.** 채울 진실이 없다 — used_on 을 옮겨 적으면 등록 시각이라는 이름으로
-- 다른 사실을 적는 셈이다. 화면은 값이 없으면 칩을 안 띄우므로 그대로도 정상 동작한다.
--
-- 정렬도 이 값으로 바뀌는데(created_at DESC, id DESC) MySQL 은 DESC 에서 NULL 을 뒤로 보낸다.
-- 그래서 새로 등록한 것이 위에 오고, 옛 행들은 그 아래에서 id 순으로 남는다 — 앱이 지금 임시로 하고
-- 있는 id 정렬과 같은 순서다.
ALTER TABLE leave_usage
    ADD COLUMN created_at DATETIME NULL COMMENT '등록 시각(KST). 이 컬럼이 생기기 전 행은 NULL';
