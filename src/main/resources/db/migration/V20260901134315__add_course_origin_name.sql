-- 코스 출발지의 **이름**(#382). 좌표는 이미 있고 이름만 없었다.
--
-- 자차 코스의 교통 카드가 "서울에서 출발" 을 못 그리던 이유다. 서버는 출발지를 위경도로만 받아 그곳을
-- 뭐라고 부르는지 모르고, 앱도 카드가 뜨는 시점(저장 코스 상세)에는 좌표를 손에 들고 있지 않다.
-- 그래서 이름이 서버를 한 번 거친다 — 저장할 때 앱이 실어 보내고, 상세에서 되돌려준다.
--
-- 서버가 좌표를 이름으로 바꾸지 않는다. 역지오코딩은 앱이 기기 내장으로 할 수 있고, 서버가 하면 외부
-- 호출이 하나 더 는다.
--
-- 기존 행은 NULL 이고 그건 오류가 아니다 — 이 필드 전에 저장된 코스이거나, 지오코딩이 실패했거나,
-- 이 필드를 모르는 앱이다. 화면은 값이 없으면 그 조각만 접는다.
ALTER TABLE course
    ADD COLUMN origin_name VARCHAR(20) NULL COMMENT '출발지 표시명(예: 서울). 앱이 역지오코딩해 보낸다';
