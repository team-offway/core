-- 출발과 도착이 같은 구간을 지운다 (#559).
--
-- ## 무엇이 문제였나
--
-- `TransitDurationService.minutesFor` 가 걸러내는 것이 수단뿐이었다. 열차·자차는 막는데
-- `depCode == arrCode` 는 안 봐서, 출발지가 그 지역 터미널과 같아지는 요청이 들어오면
-- **물어봐야 답이 없는 구간에 자리가 만들어졌다.**
--
-- 그 대가는 그 메서드 주석이 이미 적어 둔 것과 같다 — 아무도 안 읽는 행이 쌓이고, 배치가 그것을
-- 재려고 외부 한도를 태운다.
--
-- 시더(`TransitLegCandidateSeeder`)는 후보를 만들 때 이미 거르고 있었다. 같은 불변식인데
-- **조회 경로에만 없던 것**이다.
--
-- ## 운영에는 아직 없다
--
-- 실측(2026-09-13)에서 0건이었다. 조건이 맞는 요청이 아직 안 들어온 것으로 보인다.
--
-- 그래도 이 마이그레이션을 두는 이유는 **테스트가 실제로 그 행을 만들고 있었기** 때문이다 —
-- `자기_자신으로_가는_구간은_없다` 가 전체 실행 세 번 중 두 번 실패했다. 로컬·개발 DB 에는
-- 남아 있을 수 있고, 운영이 0건이면 이 문장은 아무것도 지우지 않는다.
--
-- ## 지워도 되는가
--
-- 된다. 이 표는 **캐시 성격**이다 — 없으면 배치가 다시 만들고, 그 사이 코스는 소요시간 없이 나간다
-- (곁가지라 응답이 실패하지 않는다). 게다가 여기서 지우는 행은 애초에 답이 없는 구간이라
-- 되살릴 값어치가 없다.

-- ## 비교를 코드와 같게 맞춘다
--
-- 두 컬럼의 collation 이 `utf8mb4_0900_ai_ci` 라 기본 비교가 **대소문자를 안 가린다**. 그런데 막는 쪽
-- (`minutesFor`)은 Java `String.equals` 라 가린다 — 그대로 두면 `abc` → `ABC` 같은 행을 **self-loop 이
-- 아닌데 지운다.**
--
-- 실측(2026-09-13)으로는 지금 위험이 없다. 코드가 전부 대문자(`NAEK010` 형태)라 소문자가 섞인 행이
-- 0건이고, ci·binary 어느 쪽으로 세도 지울 행이 0건이다.
--
-- 그래도 맞추는 이유는 **막는 규칙과 치우는 규칙이 어긋난 채로 두면 안 되기** 때문이다. 코드 규격이
-- 바뀌어 소문자가 섞이는 날, 이 문장은 멀쩡한 구간을 지운다.
DELETE FROM transit_leg_duration
 WHERE dep_code = arr_code COLLATE utf8mb4_bin;
