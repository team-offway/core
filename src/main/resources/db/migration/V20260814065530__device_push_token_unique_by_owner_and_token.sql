-- 푸시 토큰의 유니크 제약을 token 단독 → (guest_id, token) 복합으로 바꾼다(#264).
--
-- **왜 바꾸나.** token 단독 유니크 + INSERT ... ON DUPLICATE KEY UPDATE 는 같은 토큰이 다른 소유자로
-- 오면 소유자까지 갈아끼웠다. 뒤집으면 **남의 FCM 토큰을 아는 사람이 그것을 자기 것으로 등록해
-- 상대의 푸시를 끊고(그 행의 주인이 바뀌므로) 자기 알림을 상대 기기로 보낼 수 있다.** 지금 인증이
-- X-Guest-Id 헤더뿐이라 소유자를 사칭하는 비용도 없다.
--
-- **대가는 발송 쪽에서 갚는다.** 원래 노렸던 것은 "앱을 지웠다 깔면 게스트 ID 는 새로 발급되지만 토큰은
-- 이어질 수 있고, 그때 같은 기기에 두 행이 생기면 같은 알림이 두 번 간다" 였다. 이제 그 두 행이 실제로
-- 생긴다. 다만 그건 발송 단계에서 토큰 기준 중복 제거로 흡수되고(#270), 반대로 소유자 덮어쓰기가 여는
-- 구멍은 발송 쪽에서 막을 방법이 없다. 한쪽만 나중에 고칠 수 있으면 그쪽으로 미룬다.
--
-- **한 마이그레이션에서 add 와 drop 을 함께 한다.** 영속성 규약의 add → backfill → drop 3단계는 배포를
-- 나눠 순서 의존을 없애려는 것인데, 여기서는 (1) 채울 데이터가 없고 (2) 옛 제약을 남겨두면 그동안
-- 소유자 덮어쓰기가 그대로 살아 있어 고치는 의미가 사라지며 (3) 두 문장을 쪼개도 같은 부팅의 한
-- flyway migrate 에서 함께 적용돼 실효가 없다.
--
-- 기존 행은 token 단독으로 이미 유니크하므로 복합 유니크를 새로 걸어도 위반이 나올 수 없다.
ALTER TABLE device_push_token
    -- 소유자별로 토큰이 하나. 같은 소유자가 같은 토큰을 다시 보내면 여전히 행은 하나다(upsert 가 이 키를 탄다).
    ADD CONSTRAINT uk_device_push_token_owner_token UNIQUE (guest_id, token),
    DROP INDEX uk_device_push_token_token,
    -- 위 복합 유니크의 선두 컬럼이 guest_id 라 소유자 조회·해제가 그 인덱스를 그대로 탄다.
    -- 같은 일을 하는 인덱스를 둘 두면 쓰기 비용만 두 번 낸다.
    DROP INDEX idx_device_push_token_owner;
