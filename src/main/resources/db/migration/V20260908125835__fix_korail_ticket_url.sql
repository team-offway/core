-- 코레일 승차권 예매 링크가 명절대수송 페이지로 간다 (#498 리뷰 중 발견).
--
-- ## 무엇이 문제였나
--
-- 시드에 넣은 주소 `https://www.letskorail.com` 이 명절 기간에 `bt.korail.com/holiday/main`
-- (명절대수송)으로 리다이렉트된다. 그 칩을 누르면 **예매 화면이 아니라 명절 안내**가 뜬다.
-- `www.korail.com` 메인도 같이 넘어간다(2026-09-08 확인).
--
-- **HTTP 200 만 봐서는 못 잡는다.** 리다이렉트된 페이지가 200 으로 오기 때문이다 — #498 에서
-- 한국관광 100선이 "200 인데 본문은 404" 였던 것과 같은 결이다. 링크 검증은 상태코드가 아니라
-- **최종 도착지**를 봐야 한다.
--
-- 하위 경로는 리다이렉트를 안 타서, 예매 화면으로 바로 가는 주소를 쓴다. 출발역·도착역·출발일·인원
-- 폼이 실제로 있는 것까지 확인했다.
--
-- ## 왜 R__ 시드로 못 고치나
--
-- 이 링크는 **이미 운영 DB 에 있다**(id 3). 시드는 `ON DUPLICATE KEY UPDATE id = id` 라 있는 행을
-- 건드리지 않는다 — 어드민이 고친 값을 배포가 덮지 않게 하려는 규칙이고, 그건 그대로 옳다.
-- 그래서 이 한 건만 보정으로 고친다.
--
-- ## 어드민이 이미 고쳤으면 손대지 않는다
--
-- 조건에 **옛 주소**를 함께 건다. 누군가 백오피스에서 이미 다른 주소로 바꿔 뒀다면 그 판단이 우리보다
-- 최신이므로 덮지 않는다. `seed_key` 도 함께 봐 시드가 넣은 행만 대상으로 한다.

UPDATE curated_link
   SET link_url = 'https://www.korail.com/ticket/main'
 WHERE seed_key = 'korail-ticket'
   AND link_url = 'https://www.letskorail.com';
