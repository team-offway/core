-- 행정구역 개편 반영 — 전라남도 → 전남광주통합특별시 (#347).
--
-- 전라남도와 광주광역시가 전남광주통합특별시(시도코드 12)로 합쳐졌다. 사용자에게 보이는 시도 이름이
-- 낡아 "완도군 · 전라남도" 로 나가고 있었다.
--
-- **바꾸는 것은 이름뿐이다.** area_code(38)·legal_code(46xxx)·sigungu_code 는 그대로 둔다 —
-- 우리가 부르는 외부 API 가 아직 옛 코드만 답하기 때문이다. 실측(2026-08-28):
--
--   고흥 @202606   46770 → 100건 ✅      12740 → 0건 ❌
--   강진 @202606   46810 →  80건 ✅      12780 → 0건 ❌
--   TourAPI areaCode2 → 여전히 `38 전라남도`
--
-- 코드까지 바꾸면 전남 16곳의 중심 관광지가 통째로 빈다. 근거는 Region.legalCode 주석에 있다.
--
-- **순서가 중요하다.** V20260724112101(area_code)·V20260730085345(legal_code) 가 `sido='전라남도'` 로
-- 매칭하므로 이 마이그레이션은 그 뒤에 와야 한다. 새 DB 는 시드 → 코드 세팅 → 이 rename 순으로 돈다.
-- R__seed_program_region_tags.sql 은 repeatable 이라 versioned 전부 뒤에 돌고, 새 이름으로 매칭한다.
--
-- 광주광역시 행은 추가하지 않는다. 우리 89곳(인구감소지역)에 광주 자치구가 없다.

UPDATE region SET sido = '전남광주통합특별시' WHERE sido = '전라남도';
