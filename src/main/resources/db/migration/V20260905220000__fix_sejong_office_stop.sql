-- 세종청사가 세종고속시외버스터미널 좌표를 쓰고 있었다 (#447).
--
-- 재지오코딩(#436)이 좌표 중복 9묶음 중 여덟을 해소했는데, 이 하나가 남았다. `세종청사` 와 `세종시` 가
-- 소수점 다섯 자리까지 같은 좌표(36.46922, 127.27366)를 갖는다 — 두 지점이 한 자리에 있을 수는 없다.
--
-- 이름에 '세종' 이 들어가 도시 검증(시도 일치)을 통과했고, 장소명에 '터미널' 이 있어 터미널로도 분류됐다.
-- 실제로는 **정부세종청사정류장**(세종 한누리대로 456)이고, 터미널이 아니라 경유 정류소다.
--
-- 세종청사 고속(NAEK353)은 확인에 실패해 이미 좌표가 비어 있다 — 여기서 건드리지 않는다.
UPDATE bus_terminal SET lat = 36.50419693, lng = 127.26149071 WHERE code = 'NAI3010701';

-- 정류소다. '정부세종청사정류장' 이라 카카오 분류도 '고속,시외버스정류장' 이다(#446).
UPDATE bus_terminal SET is_terminal = FALSE WHERE code = 'NAI3010701';
